-- ==============================================================================
-- Student Database Management System Schema (Idempotent / Safe Re-run)
-- File: supabase/schema.sql
-- ==============================================================================

-- 1. Create or update the students table
create table if not exists public.students (
    id bigint generated by default as identity primary key,
    register_no text not null,
    name text not null,
    department text not null,
    year int not null check (year between 1 and 4),
    email text not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Ensure teacher_id is dropped if upgrading from previous auth schema
alter table public.students drop column if exists teacher_id cascade;

-- Ensure unique constraint on register_no
alter table public.students drop constraint if exists unique_teacher_student_register_no;
alter table public.students drop constraint if exists students_register_no_key;
alter table public.students add constraint students_register_no_key unique (register_no);

-- 2. Performance indexes
create index if not exists idx_students_register_no on public.students(register_no);
create index if not exists idx_students_name on public.students(name);

-- 3. Configure Row Level Security (RLS) for public/anon web access
alter table public.students enable row level security;

-- Drop any previous restrictive or outdated policies
drop policy if exists "Public full access to students" on public.students;
drop policy if exists "Teachers can select own students" on public.students;
drop policy if exists "Teachers can insert own students" on public.students;
drop policy if exists "Teachers can update own students" on public.students;
drop policy if exists "Teachers can delete own students" on public.students;

-- Policy: Allow all operations (SELECT, INSERT, UPDATE, DELETE) for anon public web client
create policy "Public full access to students"
    on public.students
    for all
    using (true)
    with check (true);

-- 4. Enable Realtime Replication safely (avoids ERROR 42710 if already added)
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'students'
  ) then
    alter publication supabase_realtime add table public.students;
  end if;
end $$;
