-- ==============================================================================
-- Teacher Login & Student Database Management System Schema
-- File: supabase/schema.sql
-- ==============================================================================

-- 1. Create the students table
create table if not exists public.students (
    id bigint generated by default as identity primary key,
    register_no text not null,
    name text not null,
    department text not null,
    year int not null check (year between 1 and 4),
    email text not null,
    teacher_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    constraint unique_teacher_student_register_no unique (teacher_id, register_no)
);

-- 2. Create index for faster lookups by teacher and register number
create index if not exists idx_students_teacher_id on public.students(teacher_id);
create index if not exists idx_students_register_no on public.students(register_no);

-- 3. Enable Row Level Security (RLS)
alter table public.students enable row level security;

-- 4. RLS Policies (Teacher can only access their own students)

-- Policy: SELECT
drop policy if exists "Teachers can select own students" on public.students;
create policy "Teachers can select own students"
    on public.students
    for select
    to authenticated
    using (auth.uid() = teacher_id);

-- Policy: INSERT
drop policy if exists "Teachers can insert own students" on public.students;
create policy "Teachers can insert own students"
    on public.students
    for insert
    to authenticated
    with check (auth.uid() = teacher_id);

-- Policy: UPDATE
drop policy if exists "Teachers can update own students" on public.students;
create policy "Teachers can update own students"
    on public.students
    for update
    to authenticated
    using (auth.uid() = teacher_id)
    with check (auth.uid() = teacher_id);

-- Policy: DELETE
drop policy if exists "Teachers can delete own students" on public.students;
create policy "Teachers can delete own students"
    on public.students
    for delete
    to authenticated
    using (auth.uid() = teacher_id);

-- 5. Enable Realtime Replication for the students table
alter publication supabase_realtime add table public.students;
